def sha1_name(company: str) -> str:
    """生成稳定的公司唯一 ID（模拟真实数据集的 sha1 命名）。"""
    return hashlib.sha1(f"my_set::{company}".encode("utf-8")).hexdigest()


def main():
    MERGED_DIR.mkdir(parents=True, exist_ok=True)

    # 1) 以 02_merged_reports 格式写年报（pages 结构 = PageTextPreparation 产物）
    for company, info in REPORTS.items():
        sid = sha1_name(company)
        report = {
            "metainfo": {
                "sha1_name": sid,
                "company_name": company,          # 检索路由的依据：必须与 subset.csv 一致
                "pages_amount": len(info["pages"]),
            },
            "content": {
                "chunks": None,
                "pages": [{"page": p, "text": t} for p, t in info["pages"]],
            },
        }
        (MERGED_DIR / f"{sid}.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    # 2) subset.csv（Pipeline 自动 json->csv 的逆向：直接写 csv）
    with open(MY_SET / "subset.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["sha1", "cur", "company_name", "major_industry"])
        for company, info in REPORTS.items():
            w.writerow([sha1_name(company), info["cur"], company, info["industry"]])

    # 3) questions.json
    with open(MY_SET / "questions.json", "w", encoding="utf-8") as f:
        json.dump(QUESTIONS, f, ensure_ascii=False, indent=2)

    print(f"数据集已生成: {MY_SET}")
    print(f"  公司数: {len(REPORTS)}  题目数: {len(QUESTIONS)}")


if __name__ == "__main__":
    main()
